const FORMATS = new Set(['pcf', 'xdc', 'lpf', 'qsf', 'cst']);
const ID = /^[A-Za-z_][A-Za-z0-9_$.[\]-]*$/;

function quote(value) { return String(value).replaceAll('\\', '\\\\').replaceAll('"', '\\"'); }
function periodNs(frequencyHz) { return Number((1e9 / frequencyHz).toFixed(6)); }
function natural(a, b) { return a.signal.localeCompare(b.signal, undefined, { numeric: true }); }

export function validatePlan(plan) {
  const issues = [];
  const fail = (path, message) => issues.push({ path, message });
  if (!plan || typeof plan !== 'object' || Array.isArray(plan)) return { valid: false, issues: [{ path: '$', message: 'must be an object' }] };
  if (plan.schemaVersion !== 1) fail('schemaVersion', 'must equal 1');
  if (!plan.boardId?.trim()) fail('boardId', 'is required');
  if (!Array.isArray(plan.assignments) || plan.assignments.length === 0) fail('assignments', 'must be a non-empty array');
  const signals = new Set(); const pins = new Set();
  for (const [i, item] of (plan.assignments ?? []).entries()) {
    if (!ID.test(item.signal ?? '')) fail(`assignments.${i}.signal`, 'is not a safe HDL identifier');
    if (!String(item.physicalPin ?? '').trim()) fail(`assignments.${i}.physicalPin`, 'is required');
    if (signals.has(item.signal)) fail(`assignments.${i}.signal`, 'is duplicated');
    if (pins.has(String(item.physicalPin))) fail(`assignments.${i}.physicalPin`, 'physical pin is duplicated');
    signals.add(item.signal); pins.add(String(item.physicalPin));
    if (item.driveMa != null && (!Number.isFinite(item.driveMa) || item.driveMa <= 0)) fail(`assignments.${i}.driveMa`, 'must be positive');
    if (item.pull && !['up', 'down', 'none'].includes(item.pull)) fail(`assignments.${i}.pull`, 'must be up, down, or none');
  }
  for (const [i, clock] of (plan.clocks ?? []).entries()) {
    if (!signals.has(clock.signal)) fail(`clocks.${i}.signal`, 'must reference an assigned signal');
    if (!Number.isFinite(clock.frequencyHz) || clock.frequencyHz <= 0) fail(`clocks.${i}.frequencyHz`, 'must be positive');
    if (clock.dutyCycle != null && (clock.dutyCycle <= 0 || clock.dutyCycle >= 1)) fail(`clocks.${i}.dutyCycle`, 'must be between 0 and 1');
  }
  for (const [i, delay] of (plan.ioDelays ?? []).entries()) {
    if (!signals.has(delay.signal)) fail(`ioDelays.${i}.signal`, 'must reference an assigned signal');
    if (!['input', 'output'].includes(delay.direction)) fail(`ioDelays.${i}.direction`, 'must be input or output');
    if (!Number.isFinite(delay.maxNs)) fail(`ioDelays.${i}.maxNs`, 'must be a number');
    if (delay.minNs != null && !Number.isFinite(delay.minNs)) fail(`ioDelays.${i}.minNs`, 'must be a number');
  }
  return { valid: issues.length === 0, issues };
}

export function normalizePlan(plan) {
  const result = validatePlan(plan);
  if (!result.valid) throw new Error(result.issues.map((x) => `${x.path}: ${x.message}`).join('; '));
  return {
    ...structuredClone(plan),
    assignments: [...plan.assignments].map((x) => ({ ioStandard: plan.defaultIoStandard, ...x })).sort(natural),
    clocks: [...(plan.clocks ?? [])].sort((a, b) => a.signal.localeCompare(b.signal)),
    ioDelays: [...(plan.ioDelays ?? [])].sort((a, b) => a.signal.localeCompare(b.signal))
  };
}

function header(plan, format) {
  return [`# Generated by @opencircuitlabs/constraint-generator`, `# Board: ${plan.boardId}`, `# Format: ${format.toUpperCase()}`, ''];
}

function pcf(plan) {
  const lines = header(plan, 'pcf');
  for (const a of plan.assignments) {
    const options = [];
    if (a.pull === 'up') options.push('-pullup yes');
    lines.push(`set_io ${options.join(' ')}${options.length ? ' ' : ''}${a.signal} ${a.physicalPin}`);
  }
  return lines.join('\n') + '\n';
}

function xdc(plan) {
  const lines = header(plan, 'xdc');
  for (const a of plan.assignments) {
    lines.push(`set_property PACKAGE_PIN ${a.physicalPin} [get_ports {${a.signal}}]`);
    if (a.ioStandard) lines.push(`set_property IOSTANDARD ${a.ioStandard} [get_ports {${a.signal}}]`);
    if (a.driveMa) lines.push(`set_property DRIVE ${a.driveMa} [get_ports {${a.signal}}]`);
    if (a.slew) lines.push(`set_property SLEW ${a.slew.toUpperCase()} [get_ports {${a.signal}}]`);
    if (a.pull === 'up') lines.push(`set_property PULLUP true [get_ports {${a.signal}}]`);
    if (a.pull === 'down') lines.push(`set_property PULLDOWN true [get_ports {${a.signal}}]`);
  }
  lines.push(...timingXdc(plan));
  return lines.join('\n') + '\n';
}

function lpf(plan) {
  const lines = header(plan, 'lpf');
  for (const a of plan.assignments) {
    lines.push(`LOCATE COMP "${quote(a.signal)}" SITE "${quote(a.physicalPin)}";`);
    const attrs = [];
    if (a.ioStandard) attrs.push(`IO_TYPE=${a.ioStandard}`);
    if (a.pull === 'up') attrs.push('PULLMODE=UP');
    if (a.pull === 'down') attrs.push('PULLMODE=DOWN');
    if (a.driveMa) attrs.push(`DRIVE=${a.driveMa}`);
    if (attrs.length) lines.push(`IOBUF PORT "${quote(a.signal)}" ${attrs.join(' ')};`);
  }
  return lines.join('\n') + '\n';
}

function qsf(plan) {
  const lines = header(plan, 'qsf');
  for (const a of plan.assignments) {
    lines.push(`set_location_assignment PIN_${a.physicalPin} -to ${a.signal}`);
    if (a.ioStandard) lines.push(`set_instance_assignment -name IO_STANDARD "${quote(a.ioStandard)}" -to ${a.signal}`);
    if (a.driveMa) lines.push(`set_instance_assignment -name CURRENT_STRENGTH_NEW "${a.driveMa}MA" -to ${a.signal}`);
    if (a.pull === 'up') lines.push(`set_instance_assignment -name WEAK_PULL_UP_RESISTOR ON -to ${a.signal}`);
  }
  return lines.join('\n') + '\n';
}

function cst(plan) {
  const lines = header(plan, 'cst');
  for (const a of plan.assignments) {
    lines.push(`IO_LOC "${quote(a.signal)}" ${a.physicalPin};`);
    const attrs = [a.ioStandard && `IO_TYPE=${a.ioStandard}`, a.pull === 'up' && 'PULL_MODE=UP', a.pull === 'down' && 'PULL_MODE=DOWN'].filter(Boolean);
    if (attrs.length) lines.push(`IO_PORT "${quote(a.signal)}" ${attrs.join(' ')};`);
  }
  return lines.join('\n') + '\n';
}

export function timingXdc(planInput) {
  const plan = normalizePlan(planInput);
  const lines = [];
  for (const clock of plan.clocks) {
    const period = periodNs(clock.frequencyHz); const high = Number((period * (clock.dutyCycle ?? 0.5)).toFixed(6));
    lines.push(`create_clock -name ${clock.name ?? clock.signal} -period ${period} -waveform {0 ${high}} [get_ports {${clock.signal}}]`);
  }
  for (const delay of plan.ioDelays) {
    const cmd = delay.direction === 'input' ? 'set_input_delay' : 'set_output_delay';
    const clock = delay.clock ? ` -clock [get_clocks {${delay.clock}}]` : '';
    lines.push(`${cmd} -max ${delay.maxNs}${clock} [get_ports {${delay.signal}}]`);
    if (delay.minNs != null) lines.push(`${cmd} -min ${delay.minNs}${clock} [get_ports {${delay.signal}}]`);
  }
  for (const path of plan.falsePaths ?? []) lines.push(`set_false_path -from [get_${path.fromType ?? 'ports'} {${path.from}}] -to [get_${path.toType ?? 'ports'} {${path.to}}]`);
  return lines;
}

export function timingSdc(planInput) {
  const plan = normalizePlan(planInput); const lines = header(plan, 'sdc');
  for (const clock of plan.clocks) {
    const period = periodNs(clock.frequencyHz);
    lines.push(`create_clock -name ${clock.name ?? clock.signal} -period ${period} [get_ports {${clock.signal}}]`);
  }
  lines.push(...timingXdc({ ...plan, clocks: [] }));
  return lines.join('\n') + '\n';
}

export function generateConstraints(planInput, format, options = {}) {
  format = format.toLowerCase();
  if (!FORMATS.has(format)) throw new Error(`Unsupported format ${format}; expected ${[...FORMATS].join(', ')}`);
  const plan = normalizePlan(planInput);
  const pinText = ({ pcf, xdc, lpf, qsf, cst })[format](plan);
  return { format, extension: format, content: pinText, timing: options.includeSdc ? timingSdc(plan) : null };
}

export function planFromRegistryAssignment(result, options = {}) {
  return {
    schemaVersion: 1,
    boardId: result.boardId,
    defaultIoStandard: options.defaultIoStandard,
    assignments: result.assignments.map((a) => ({ signal: a.signal, physicalPin: a.physicalPin, ioStandard: a.ioStandard ?? options.defaultIoStandard, activeLow: a.activeLow })),
    clocks: options.clocks ?? [], ioDelays: options.ioDelays ?? [], falsePaths: options.falsePaths ?? []
  };
}
